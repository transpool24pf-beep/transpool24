export function odMailT(locale: AdminLocale, key: keyof typeof MAIL_DE, vars?: { eur?: string }): string {
  const m = locale === "ar" ? MAIL_AR : MAIL_DE;
  let s = m[key] ?? MAIL_DE[key] ?? key;
  if (vars?.eur != null) s = s.replace("{eur}", vars.eur);
  return s;
}

