export const GERMANY_CITY_NAMES: string[] = GERMANY_CITIES.map((c) => c.name);

export const GERMANY_CITY_COORDS: Record<string, [number, number]> = Object.fromEntries(
  GERMANY_CITIES.map((c) => [c.name, [c.lat, c.lon] as [number, number]])
);

const UMLAUT: Record<string, string> = { ä: "a", ö: "o", ü: "u", ß: "ss", Ä: "a", Ö: "o", Ü: "u" };

export function foldCityQuery(s: string): string {
  return s.replace(/[äöüßÄÖÜ]/g, (ch) => UMLAUT[ch] ?? ch).toLowerCase().trim();
}

const FEATURED = [
  "Pforzheim",
  "Stuttgart",
  "Karlsruhe",
  "Mannheim",
  "Heidelberg",
  "Esslingen am Neckar",
  "Ludwigsburg",
  "Sindelfingen",
  "Böblingen",
  "Leonberg",
  "Waiblingen",
  "Fellbach",
  "Heilbronn",
  "Reutlingen",
  "Tübingen",
];

export function searchGermanyCities(query: string, limit = 40): string[] {
  const q = foldCityQuery(query);
  if (!q) {
    const featured = FEATURED.filter((n) => GERMANY_CITY_NAMES.includes(n));
    return featured;
  }
  const starts: string[] = [];
  const contains: string[] = [];
  for (const name of GERMANY_CITY_NAMES) {
    const f = foldCityQuery(name);
    if (f.startsWith(q)) starts.push(name);
    else if (tokenContains(f, q)) contains.push(name);
  }
  return [...starts, ...contains].slice(0, limit);
}

function tokenContains(folded: string, q: string): boolean {
  let i = folded.indexOf(q);
  while (i !== -1) {
    if (i === 0 || /[\s\-/(]/.test(folded[i - 1] ?? "")) return true;
    i = folded.indexOf(q, i + 1);
  }
  return false;
}

